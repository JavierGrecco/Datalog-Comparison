import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { generateSimulatedTelemetry, serializeSimulatedTelemetryCsv } from "../src/simulated-telemetry.mjs";

const HELP = [
  "Uso: npm run simulate:telemetry -- [opciones]",
  "--profile ecu|obd           ECU uniforme u OBD con PID asíncronos",
  "--scenario road-test|sensor-dropout",
  "--duration SEGUNDOS         Duración entre 0 y 1800",
  "--rate HZ                   Frecuencia ECU, entero de 1 a 100 (default 20)",
  "--seed ENTERO               Semilla reproducible (default 42)",
  "--output RUTA               Ruta CSV opcional",
  "--help",
].join("\n");

export function parseSimulatorCliArgs(args) {
  const options = { profile: "ecu", scenario: "road-test", durationSeconds: 120, sampleRateHz: 20, seed: 42 };
  let outputPath = null;
  let help = false;
  const numeric = { "--duration": "durationSeconds", "--rate": "sampleRateHz", "--seed": "seed" };
  for (let i = 0; i < args.length; i += 1) {
    const key = args[i];
    if (key === "--help" || key === "-h") { help = true; continue; }
    if (key === "--output") {
      if (!args[i + 1] || args[i + 1].startsWith("--")) throw new Error("--output requiere una ruta.");
      outputPath = args[++i];
      continue;
    }
    if (key === "--profile" || key === "--scenario") {
      if (!args[i + 1] || args[i + 1].startsWith("--")) throw new Error(key + " requiere un valor.");
      options[key === "--profile" ? "profile" : "scenario"] = args[++i];
      continue;
    }
    if (Object.hasOwn(numeric, key)) {
      if (!args[i + 1] || args[i + 1].startsWith("--")) throw new Error(key + " requiere un número.");
      const value = Number(args[++i]);
      if (!Number.isFinite(value)) throw new Error(key + " debe ser numérico.");
      options[numeric[key]] = value;
      continue;
    }
    throw new Error("Argumento desconocido: " + key);
  }
  return { options, outputPath, help };
}

async function run(args) {
  const parsed = parseSimulatorCliArgs(args);
  if (parsed.help) { process.stdout.write(HELP + "\n"); return; }
  const dataset = generateSimulatedTelemetry(parsed.options);
  const csv = serializeSimulatedTelemetryCsv(dataset);
  const csvPath = parsed.outputPath
    ? (isAbsolute(parsed.outputPath) ? parsed.outputPath : resolve(process.cwd(), parsed.outputPath))
    : resolve(process.cwd(), "data/generated/simulated-" + dataset.metadata.profile + "-" + dataset.metadata.scenario + ".csv");
  const metadataPath = csvPath + ".metadata.json";
  const metadata = {
    ...dataset.metadata,
    generatedAt: new Date().toISOString(),
    output: csvPath,
    sha256: createHash("sha256").update(csv, "utf8").digest("hex"),
    attribution: "Synthetic data generated by Datalog Comparison; no external dataset is included.",
    limitations: [...dataset.metadata.omissions, "Model outputs are illustrative software test signals, not physical evidence."],
  };
  await mkdir(dirname(csvPath), { recursive: true });
  await writeFile(csvPath, csv, "utf8");
  await writeFile(metadataPath, JSON.stringify(metadata, null, 2) + "\n", "utf8");
  process.stdout.write("CSV: " + csvPath + "\nMetadata: " + metadataPath +
    "\nRows: " + dataset.rows.length + "\nSHA-256: " + metadata.sha256 + "\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  run(process.argv.slice(2)).catch(error => {
    process.stderr.write(error.message + "\n" + HELP + "\n");
    process.exitCode = 1;
  });
}
