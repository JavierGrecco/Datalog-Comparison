import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { generateSimulatedDyno, serializeSimulatedDynoCsv } from "../src/simulated-dyno.mjs";

const HELP = [
  "Uso: npm run simulate:dyno -- [opciones]",
  "--mode graph-export|time-export  Incremento RPM o intervalo temporal",
  "--scenario reference|candidate|sensor-dropout|repeat-pulls",
  "--rpm-start RPM --rpm-end RPM --rpm-step RPM",
  "--duration SEGUNDOS --interval-ms MILISEGUNDOS --seed ENTERO",
  "--output RUTA --help",
].join("\n");

export function parseDynoSimulatorCliArgs(args) {
  const options = {
    mode: "graph-export", scenario: "reference", seed: 42,
    rpmStart: 1800, rpmEnd: 6500, rpmStep: 50,
    durationSeconds: 8, sampleIntervalMs: 50, measurementBasis: "wheel",
  };
  const numeric = {
    "--rpm-start": "rpmStart", "--rpm-end": "rpmEnd", "--rpm-step": "rpmStep",
    "--duration": "durationSeconds", "--interval-ms": "sampleIntervalMs", "--seed": "seed",
  };
  let outputPath = null, help = false;
  for (let i = 0; i < args.length; i += 1) {
    const key = args[i];
    if (key === "--help" || key === "-h") { help = true; continue; }
    if (key === "--output") {
      const value = args[i + 1];
      if (!value || value.startsWith("--")) throw new Error("--output requiere una ruta.");
      outputPath = args[++i]; continue;
    }
    if (key === "--mode" || key === "--scenario") {
      const value = args[i + 1];
      if (!value || value.startsWith("--")) throw new Error(key + " requiere un valor.");
      options[key === "--mode" ? "mode" : "scenario"] = args[++i]; continue;
    }
    if (Object.hasOwn(numeric, key)) {
      const value = args[i + 1];
      if (!value || value.startsWith("--") || !Number.isFinite(Number(value))) {
        throw new Error(key + " requiere un número válido.");
      }
      options[numeric[key]] = Number(value); i += 1; continue;
    }
    throw new Error("Argumento desconocido: " + key);
  }
  return { options, outputPath, help };
}

async function run(args) {
  const parsed = parseDynoSimulatorCliArgs(args);
  if (parsed.help) { process.stdout.write(HELP + "\n"); return; }
  const dataset = generateSimulatedDyno(parsed.options);
  const csv = serializeSimulatedDynoCsv(dataset);
  const csvPath = parsed.outputPath
    ? (isAbsolute(parsed.outputPath) ? parsed.outputPath : resolve(process.cwd(), parsed.outputPath))
    : resolve(process.cwd(), "data/generated/simulated-dyno-" +
      dataset.metadata.exportMode + "-" + dataset.metadata.scenario + ".csv");
  const metadata = {
    ...dataset.metadata,
    generatedAt: new Date().toISOString(),
    output: csvPath,
    sha256: createHash("sha256").update(csv, "utf8").digest("hex"),
    attribution: "Synthetic data generated by Datalog Comparison; no external measurement data is included.",
  };
  await mkdir(dirname(csvPath), { recursive: true });
  await writeFile(csvPath, csv, "utf8");
  await writeFile(csvPath + ".metadata.json", JSON.stringify(metadata, null, 2) + "\n", "utf8");
  process.stdout.write("CSV: " + csvPath + "\nMetadata: " + csvPath +
    ".metadata.json\nRows: " + dataset.rows.length + "\nSHA-256: " + metadata.sha256 + "\n");
}

